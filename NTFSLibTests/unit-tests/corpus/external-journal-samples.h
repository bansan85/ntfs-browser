// One journal record as an independent reader (a small Python parser that
// never ran this library) decoded it from a real $J. Every field is a fact
// about the fixture.
struct JournalSample {
  // Position among the journal's V2 and V3 records, counted from 0.
  std::size_t index;
  // Byte offset of the record in the fixture file.
  std::uint64_t offset;
  LONGLONG usn;
  ULONGLONG file_record;
  WORD file_sequence;
  ULONGLONG parent_record;
  WORD parent_sequence;
  // Time of the event in UTC, as microseconds since 1601-01-01. The reader
  // keeps no finer unit.
  std::uint64_t utc_microseconds;
  DWORD reason;
  DWORD attributes;
  std::string_view name;
};

